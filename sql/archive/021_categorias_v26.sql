-- 4. Migrar category_id de empresas cuyos slugs cambiaron
UPDATE businesses b
SET category_id = new_cat.id
FROM cat_migration m
JOIN categories old_cat ON old_cat.slug = m.old_slug
JOIN categories new_cat ON new_cat.slug = m.new_slug
WHERE b.category_id = old_cat.id;

